                                # 位置未收敛，每次清除动作后顺路补测一次（多视角缩小区域，利于后续
                                # 清除）。实测：扫描布局已让多数频道定位充分，每局候选 ~10 个、真正
                                # 可获信息 ~7 个（距估计点 >1500 m 的必然无信号，理性跳过）。
