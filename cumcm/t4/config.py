"""问题四的全部可调参数与物理常量。

问题四与问题三共用同一份题目物理设定（区域半径、接收半径、测向误差、时间常量），唯一的结构
差异是引入了**定向干扰源**：定向源只在"定向方向 ±90°"（全角 180°）内有信号，方向之外一律
收不到。由此带来两处与问题三不同的建模口：

1. **no_signal 不再是"源在接收半径之外"的硬约束**。问题三全是全向源，收不到 ⇒ 距源 > 1000 m
   （见 cumcm.t3.regions 的 add_outside）；问题四里"收不到"既可能是太远、也可能是**方向不对**
   （机器狗站在定向源背面）。因此本题的定位区域只用"direction（楔形 + 接收半径内包）"与
   "near（≤ 5 m）"两类硬约束，no_signal 一律不作为区域约束（见 cumcm.t4.regions.DirProbRegion）。
2. **检测阶段必须是"保证命中任意半圆盘"的寻向拖网**。定向源的检测区 = 接收圆 ∩ 前向半平面
   （半圆盘），圆心、半径（1000~1500）、朝向全部未知；固定几个巡视点无法保证不漏定向源
   （问题三的 7 点覆盖对"背对着所有巡视点的源"必然漏听）。本题用 700 m 栅格拖网 + 边界环
   覆盖圆域，使**任意**半圆盘（任意中心、任意朝向、半径 ≥ 1000）都被某个测量点命中，全部
   参数与校验见 cumcm.t4.sweep。

所有常量集中在此，便于"一处改、全局生效"。凡是经过实验选定或校准的常量，都在注释里保留依据。
"""

from __future__ import annotations

import math

from typing import Tuple

# ----------------------------------------------------------------------------
# 题目物理设定（与问题三一致，见 cumcm.t3.config，这里按分量重述以免 t4 → t3 依赖）
REGION_RADIUS = 1800.0          # 目标圆域半径 / m
