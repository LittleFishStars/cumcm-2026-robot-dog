OUTER_RING_RAD = 1850.0         # 外圈半径 / m（贴边源迎光区内沿 1770 m 之内的近邻）
# 每频道在扫描阶段最多采集的示向度条数。问题四定向源只有"迎面一侧"能测到，多视角对交会定位
