# 检测布局：7 个覆盖基点（复用问题三 t3.config.SURVEY_CENTERS 的巡视站）+ 任意两两基点的中点
# 沿径向外推 EXTEND_K 倍（模长上限 EXTEND_CLAMP）作为加密测量点。为什么外推中点：
#   * 定向源检测区是半径 ≥ 1000 的半圆盘；它朝外的部分（含圆域外 470 m 附近）才是"迎光面"，
#     原样中点全挤在 |p| ≤ 1241 的内部，对边缘迎光区几乎无帮助（实测听到率仅 82.8%）；
#   * 沿径向把中点推到 |p| ~ 2200 后，周围 21 个方向都补上了外部迎光区，实测听到率 99.81%
#     （20 万样本蒙特卡洛，见 cumcm.t4.sweep.verify_hearing_stats）；
#   * 这是"尽量复用问题三覆盖布局"的折中：不再是 37 点拖网的严格保证（131 万算例 0 失败），
#     而是轻量加密（28+1 点），论文按实测听到率报告，不声称严格不漏。
