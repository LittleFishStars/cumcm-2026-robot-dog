"""问题四的全部可调参数与物理常量。

问题四与问题三共用同一份题目物理设定（区域半径、接收半径、测向误差、时间常量），唯一的结构
差异是引入了**定向干扰源**：定向源只在"定向方向 ±90°"（全角 180°）内有信号，方向之外一律
收不到。由此带来两处与问题三不同的建模口：

1. **no_signal 不再是"源在接收半径之外"的硬约束**。问题三全是全向源，收不到 ⇒ 距源 > 1000 m
   （见 cumcm.t3.regions 的 add_outside）；问题四里"收不到"既可能是太远、也可能是**方向不对**
   （机器狗站在定向源背面）。因此本题的定位区域只用"direction（楔形 + 接收半径内包）"与
   "near（≤ 5 m）"两类硬约束，no_signal 一律不作为区域约束（见 cumcm.t4.regions.DirProbRegion）。
2. **检测阶段复用问题三的 7 点覆盖，并按"尽量减少路程"优化外圈**。定向源的检测区 = 接收圆
   ∩ 前向半平面（半圆盘），圆心、半径（1000~1500）、朝向全部未知；固定 7 个覆盖点无法保证
   不漏定向源（问题三的 7 点覆盖对"背对着所有巡视点的源"必然漏听，实测听到率仅 80.7%）。
   本方案**复用问题三的 7 个覆盖基点**，外圈改为 OUTER_RING_N 个均匀方位的 1850 m 点
   （20 个测量位置、访问里程 17 019 m，比"7 基点 + 21 中点外推"的 29 点 / 21 580 m 省 21%）：
   1850 m 正落在任意贴边源的迎光区内沿（1770 m 是源最远半径），12 个方位（30° 间隔）保证
   任意方向的源都能被方向差 ≤ 15° 的外圈点听到，实测听到率 ~99.99%（400 万蒙特卡洛 +
   43 万对抗算例、贴边对抗 0 漏）——这是"尽量复用问题三布局 + 路程最小化"的轻量折中，
   全部参数与统计校验见 cumcm.t4.sweep（**非严格保证**，论文按实测报告）。

所有常量集中在此，便于"一处改、全局生效"。凡是经过实验选定或校准的常量，都在注释里保留依据。
"""

