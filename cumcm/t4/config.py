RECEIVE_MAX = 1500.0            # 有效接收半径上界 / m（题目给定 1000~1500）
RECEIVE_MID = 0.5 * (COVER_RADIUS + RECEIVE_MAX)    # 接收半径中值，用于估源距离 / m
