# 检测布局：原点（起点全频道扫描）+ 7 个覆盖基点（复用问题三 t3.config.SURVEY_CENTERS 的
# 巡视站）+ OUTER_RING_N 个半径 OUTER_RING_RAD 的**均匀方位外圈点**（20 个测量位置）。为什么
# 外圈取半径 1850 m、12 个方位：
#   * 定向源检测区是半径 ≥ 1000 的半圆盘；"迎光面"在源前方 [|g|, |g|+R] 纵深。源最远半径
#     1770，故**任意**贴边源的迎光区内沿 = 1770 m，外圈设在其内侧 1850 m 覆盖全部源的迎光区
#     （径向偏差 < 80 m）；
#   * 方位分辨率：源在方向 φ、半径 |g| 的迎光区被方向差 δ ≤ 30° 的外圈点覆盖（相邻点最大
#     距离 ≈ 1850·sin15° ≈ 479 m < 接收半径 1000 m 的一半），12 个方位（间隔 30°）足够；
#   * 实测（cumcm.t4.sweep.verify_hearing_stats）：听到率 99.99%（400 万蒙特卡洛、4 个随机
#     seed 稳健），贴边对抗 4.3 万例 0 漏；访问里程 17.0 km —— 比"7 基点 + 21 中点外推"
#     （29 点、21.6 km、99.81%）路程省 21%、听到率更高。
