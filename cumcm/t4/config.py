# ----------------------------------------------------------------------------
# 检测阶段的寻向拖网（本问题相对问题三的核心改动，见 cumcm.t4.sweep）
# 为什么栅距 700 m：定向源检测区是半径 ≥ 1000 的半圆盘，其内切圆半径 = R/2 ≥ 500；方形栅格
# 的覆盖半径 ρ = 栅距/√2 ≤ 500 ⟺ 栅距 ≤ 707 m，于是任意半圆盘的内切圆内必有一个栅格测量点。
# 为什么格点取到半径 2270 m（圆域外 470 m）：R = 1000 m 时内切圆圆心的最远位置 = 源最远半径
# (1770) + 500 = 2270 m；格点必须把以任何该圆心、半径 ≥ 500 的圆都覆盖到，故取 |p| ≤ 2270 的
# 整个 700 m 格点（含圆域外）——这样解析保证严格成立：任意 (g, θ, R ≥ 1000) 的半圆盘都被命中。
# 覆盖校验（triple check，全部 0 失败）见 cumcm.t4.sweep.verify_detection_guarantee：
#   181440 个精细对抗算例（最坏命中深度 0.792）+ 129600 个贴边对抗算例（深度 0.566）
#   + 100 万蒙特卡洛。
SWEEP_SPACING = 700.0           # 栅格间距（x/y 两个方向） / m
GRID_LATTICE_RAD = 2270.0       # 格点保留半径 / m（> 1800，覆盖内切圆圆心可达域，保解析保证）
# 每频道在拖网阶段最多采集的示向度条数。问题四定向源只有"迎面一侧"能测到，多视角对交会定位
# 更宝贵（弥补"半圆盘内可测点少"），但要为收尾定位保留预算，取 4 是实测折中。
