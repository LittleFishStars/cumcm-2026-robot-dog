# 拖网阶段"顺路补测"半径：已听到但视角不足的频道，若当前拖网点落在其估计点该半径内，则顺路
# 补一次测向（多一条不同角度的射线）。定向源只有迎光侧可听，补测额外视角对交会定位帮助很大。
SWEEP_OPP_RADIUS = 1200.0

# 示向度误差（题目附录 2 第 1 条：|误差| ≤ 1°，同点同频道固定）
BEARING_ERROR_DEG = 1.0
