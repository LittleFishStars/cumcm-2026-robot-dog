# ---- 第二阶段常量：定位区域、清除判据、补测选点准则（文献方法）----
# ---- 示向度误差模型：完全按题面照抄，不引入题面之外的任何假设 ----
# 题面（B 题）原文："由于环境影响及测向精度所限，测向机的读数会受到当地电磁环境的影响，使得
# 测向机测得的示向度与干扰源的最大场强方向的真实方位角之间存在一定的误差。在一段时间内，
# 同一地点的电磁环境干扰是固定的，所以重复检测不会改变检测误差。只有在不同地点、不同电磁
# 环境下，误差才会呈现统计规律。从目标区域全局来看，所有这些误差在 [−1°, 1°] 范围内。"
#
# 由此确定的建模前提（本程序的全部推理只用这三条）：
#   (a) 误差是"地点"的属性 —— 同一地点重复测量得到同一个误差 ⇒ 同点复测无增量信息；
#   (b) 误差在 [−1°, 1°] 内，且在不同地点"呈现统计规律" ⇒ 视为随机变量，取对称分布
#       （自然取均匀分布 U(−1°, 1°)，σ = 1/√3 ≈ 0.577°，下面就用它做 Fisher 权重）；
#   (c) 题面未给出误差在空间上的相关结构，故按统计均匀（同分布且不随位置系统变化）处理 ——
#       这也是唯一不引入题外假设的处理方式。
# 注意 (b)(c) 意味着"误差的方差与测量点位置无关"，因此任何"把测量点摆到某处以降低误差方差"
# 的想法都不在本题模型之内，本程序不做这种主张。
BEARING_ERROR_DEG = 1.0         # 示向度误差半宽 / 度（题面给定 |误差| ≤ 1°，楔形张角 2°）
# 误差的量级，**只作统一的尺度因子**用，不承担"绝对量"的含义：
#   * Fisher 权重的尺度：J = Σ nᵢnᵢᵀ/(σ²rᵢ²) 里 σ 只以整体因子 1/σ² 出现，选点靠的是各候选
#     点之间 σ 的**相对**大小（probe_candidates 用 c.sigma ≤ best×1.02 与 sigma 排序），
#     故 σ 取 1° 还是取均匀分布的标准差 1/√3° 都得到完全相同的选点结果；
#   * 文献模糊区公式里的 Δθ 是**误差半宽**（题面口径），故这里必须保持半宽 1°，不能用 σ。
# 两个角色数值不同（1° 与 1/√3°），若混用会改变 ambiguity_area 的对照值，故统一取半宽 1°
# 并在此写明：它作为尺度因子时是任意的，作为 Δθ 时是题面给定的。
