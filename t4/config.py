# 检测布局：原点做起点全频道扫描，加 7 个覆盖基点，复用问题三 t3.config.SURVEY_CENTERS 的巡视
# 站，加 OUTER_RING_N 个半径 OUTER_RING_RAD 的均匀方位外圈点。为什么外圈取 1850 m、12 个方位？
#
# 12 个方位是"减少路程"的实战最优。曾试过 11 点，布局路线虽短 294 m，但方位间隔拉到 32.7°，
# 顺路清除扇区跟着变宽、绕路更多，实战总里程反升 464 m，已回滚。理由如下：
#   * 定向源检测区是半径 ≥ 1000 的半圆盘，"迎光面"落在源前方 [|g|, |g|+R] 的纵深里。源最远半径
#     1770，所以任意贴边源的迎光区内沿 = 1770 m。外圈设在其内侧 1850 m，覆盖全部源的迎光区，
#     径向偏差 < 80 m；
#   * 方位分辨率：源在方向 φ、半径 |g| 的迎光区，会被方向差 δ ≤ 30° 的外圈点覆盖。相邻点最大
#     距离 ≈ 1850·sin15° ≈ 479 m，不到接收半径 1000 m 的一半，所以 12 个方位、间隔 30° 够用；
#   * 实测见 t4.sweep.verify_hearing_stats：听到率 99.9891%，422.5 万算例漏 460，其中 400 万
#     蒙特卡洛漏 320 + 精细对抗漏 140 + 贴边对抗 4.3 万例 0 漏；访问里程 16 995.65 m，比
#     "7 基点 + 21 中点外推"的 29 点 / 21.6 km / 99.81% 省 21% 路程、听到率还更高。
#   * 为什么不再加内部补点：3 个内部补点，r = 850 m，曾把听到率提到 99.9974%，但 20 局演练实测
#     反而慢 80 s，多出 ~34 次测向时的 no_signal 试探。对每局 16 个源的任务，99.9891% 的漏率
#     意味着每 20 局 256 个源期望漏 0.03 个源，而 20 局实测 256/256 全清，耗时与完成率双优，
#     所以定案 20 点版。神经网络独立搜索也没找到更省时的布局，见报告 3.6 节。
OUTER_RING_N = 12               # 外圈测量点个数 / 个，均匀方位，间隔 30°
