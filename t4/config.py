# 途中顺路清除，沿用问题三优化后的机制与参数，见 t3.strategy 与 config，2026-09-12 同步。
#   · 站点间前向，本站→下一站：以区域圆心也就是原点为参照的方位扇区，见 _in_azimuth_arc。估计点
#     与圆心的连线方向落在「本站→圆心」到「下一站→圆心」两条连线之间，取较短弧，就算顺路；估计
